#!/usr/bin/env python3
"""Generate deterministic Reference pages from WaveBench machine facts."""

from __future__ import annotations

import argparse
import sys
from pathlib import Path


REPOSITORY_ROOT = Path(__file__).resolve().parents[1]
SOURCE_ROOT = REPOSITORY_ROOT / "src"
TARGET = REPOSITORY_ROOT / "docs" / "reference" / "generated" / "run-schema.md"

if str(SOURCE_ROOT) not in sys.path:
    sys.path.insert(0, str(SOURCE_ROOT))


def _format_run_plan_schema() -> str:
    from wavebench.services.run_plan import format_run_plan_schema

    return format_run_plan_schema()


def render_run_schema_page() -> str:
    """Return the checked-in representation of the current run-plan schema."""

    schema = _format_run_plan_schema().rstrip()
    return "\n".join(
        (
            "<!-- Generated by scripts/generate_docs.py; do not edit by hand. -->",
            "# Generated run plan schema",
            "",
            "本页由 `src/wavebench/services/run_plan.py:format_run_plan_schema()` 生成。",
            "手写的使用说明见[run plan Reference](../run-schema.md)。",
            "",
            "```text",
            schema,
            "```",
            "",
        )
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail when generated Reference differs from the checked-in file",
    )
    args = parser.parse_args(argv)
    expected = render_run_schema_page()

    if args.check:
        if TARGET.is_file() and TARGET.read_text(encoding="utf-8") == expected:
            print(f"generated Reference is current: {TARGET.relative_to(REPOSITORY_ROOT)}")
            return 0
        print(
            f"generated Reference is out of date: {TARGET.relative_to(REPOSITORY_ROOT)}; "
            "run `python scripts/generate_docs.py`",
            file=sys.stderr,
        )
        return 1

    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(expected, encoding="utf-8")
    print(f"generated Reference: {TARGET.relative_to(REPOSITORY_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
